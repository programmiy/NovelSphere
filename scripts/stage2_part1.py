def run_part1():
    items, _ = get_items(limit=1000)
    by_id = {x["id"]: x for x in items}
    to_insert = []
    for tid, text in PART1_TRANSLATIONS.items():
        it = by_id.get(tid)
        if not it:
            continue
        if CJK_PATTERN.search(text):
            raise ValueError(f"CJK detected in ID {tid}: {text}")
        cls_res = classify_translation(it["original"], text)
        if cls_res != "normal":
            raise ValueError(f"Classifier failed for ID {tid}: {cls_res} -> {text}")
        to_insert.append({"id": tid, "reviewed_translation": text})

    print(f"Verified {len(to_insert)} Part 1 items.")
    cnt = insert_reviewed(to_insert, model_name="Antigravity-AI")
    print(f"SUCCESS: Inserted {cnt} Part 1 items!")


if __name__ == "__main__":
    run_part1()
